#include <iostream>

using namespace std;
/*
    inline함수 : 함수 본문을 호출하지 않고, 호출 자리에 코드를 삽입하는 함수

    현대에 들어, "링크 오류"를 방지하기 위한 목적으로 사용한다.
    (링커가 obj파일을 합칠 때, 같은 이름의 함수가 여러개 존재하면 발생하는 오류)
    
    inline 함수는 "여러 파일에 같은 정의가 있어도 괜찮다, 링커가 하나만 골라 쓴다"는 규칙을 따른다.
    단, 모든 파일에서 같은 이름의 함수는, 정의 내용도 같아야 한다.
*/
/*
    장점
    - 함수 호출 비용 절감, 미리 계산 가능
    
    단점
    - 호출이 많아지면 코드 크기가 커질 수 있음
    - 수정 시 포함한 모든 파일이 다시 컴파일되어야함.

    => 짧고, 자주 호출되는 함수에 적합 : Getter, Setter
*/
inline int I_MUL(int x, int y) {
	return x * y;
}

int main(void) {
    int a = I_MUL(1, 2); // inline함수 호출
    // 인라인 확장되면 컴파일러는 사실상 아래처럼 바꿔서 컴파일함
    // int a = 1 * 2;
    cout << a << endl;
	return 0;
}